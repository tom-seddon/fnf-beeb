#!/usr/bin/python3
# Generate the tables used to play TIA sound on the BBC's SN76489.
#
# TIA: each channel has AUDC (waveform), AUDF (0-31, frequency divider)
# and AUDV (0-15, volume). The audio clock is 31399.5Hz (NTSC). Pure
# tones come out at clock/(AUDF+1)/D, D depending on AUDC; the noise
# waveforms shift a polynomial counter at clock/(AUDF+1).
#
# SN76489 on the BBC: 4MHz clock, so tone channel frequency is
# 125000/N for a 10-bit period N (1-1023). Noise can be clocked by tone
# channel 2's output, i.e. shift at 125000/N too. Attenuation 0-15, in
# 2dB steps, 15 = off.
#
# Kinds (index into the period table, 32 entries each):
#
#   0 silent       AUDC 0, 11
#   1 noise        AUDC 1, 2, 3, 7, 8, 9, 15 (all treated as white noise)
#   2 tone, D=2    AUDC 4, 5
#   3 tone, D=6    AUDC 12, 13
#   4 tone, D=31   AUDC 6, 10
#   5 tone, D=93   AUDC 14
#
# Tones too low for the SN76489 (N>1023) go up an octave at a time.

import argparse,math

TIA_AUDIO_CLOCK=3579545/114
SN_TONE_CLOCK=4000000/32

KIND_SILENT,KIND_NOISE,KIND_DIV2,KIND_DIV6,KIND_DIV31,KIND_DIV93=range(6)
NUM_KINDS=6

AUDC_KINDS=[KIND_SILENT,KIND_NOISE,KIND_NOISE,KIND_NOISE,
            KIND_DIV2,KIND_DIV2,KIND_DIV31,KIND_NOISE,
            KIND_NOISE,KIND_NOISE,KIND_DIV31,KIND_SILENT,
            KIND_DIV6,KIND_DIV6,KIND_DIV93,KIND_NOISE]

DIVISORS={KIND_NOISE:1,KIND_DIV2:2,KIND_DIV6:6,KIND_DIV31:31,KIND_DIV93:93}

def get_period(kind,audf):
    if kind==KIND_SILENT: return 0
    freq=TIA_AUDIO_CLOCK/(audf+1)/DIVISORS[kind]
    n=round(SN_TONE_CLOCK/freq)
    while n>1023: n=round(n/2)
    return max(n,1)

def get_attenuation(audv):
    if audv==0: return 15
    # TIA volume is roughly linear amplitude.
    db=-20*math.log10(audv/15)
    return min(14,round(db/2))

def main(options):
    with open(options.output,'wt') as f:
        f.write('; Generated by tools/make_sn_tables.py - do not edit.\n\n')

        f.write('; Sound kind for each AUDC value.\n')
        f.write('audc_kinds:\n')
        for audc,kind in enumerate(AUDC_KINDS): f.write('                .byte %d ; AUDC %d\n'%(kind,audc))
        f.write('sound_kind_silent=%d\n'%KIND_SILENT)
        f.write('sound_kind_noise=%d\n\n'%KIND_NOISE)

        f.write('; SN76489 attenuation for each AUDV value.\n')
        f.write('audv_attenuations:\n')
        for audv in range(16): f.write('                .byte %d ; AUDV %d\n'%(get_attenuation(audv),audv))
        f.write('\n')

        periods=[get_period(kind,audf) for kind in range(NUM_KINDS) for audf in range(32)]
        f.write('; SN76489 period for each kind*32+AUDF.\n')
        for name,shift in (('lo',0),('hi',8)):
            f.write('tia_sn_periods_%s:\n'%name)
            for i in range(0,len(periods),8):
                f.write('                .byte %s\n'%','.join('$%02x'%((p>>shift)&0xff) for p in periods[i:i+8]))
        f.write('\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description='generate TIA->SN76489 sound tables')
    parser.add_argument('output',metavar='FILE',help='write 64tass source to %(metavar)s')
    main(parser.parse_args())
