#!/usr/bin/python3
# Generate the TIA colour -> BBC physical colour table used by
# set_role_colour on a stock (non-VideoNuLA) BBC.
#
# There are only 8 colours to pick from, so straight nearest-RGB
# matching doesn't work well (the game's mid greens and khaki all come
# out black). Instead, classify by hue/saturation/value:
#
# - dark (max channel < DARK) -> black
# - unsaturated -> white or black, by brightness
# - otherwise the nearest of the 6 primary/secondary hues
#
# The sky ($9x) and water ($7x) families sit either side of the
# cyan/blue boundary, so they come out cyan and blue respectively.

import sys,os,argparse
sys.path.append(os.path.dirname(os.path.realpath(__file__)))
import tia_palette

DARK=0x50
GREY_SATURATION=0.3
GREY_WHITE=0x90

BLACK,RED,GREEN,YELLOW,BLUE,MAGENTA,CYAN,WHITE=range(8)

# (upper hue bound in degrees, BBC colour)
HUES=[(30,RED),
      (90,YELLOW),
      (165,GREEN),
      (230,CYAN),
      (285,BLUE),
      (345,MAGENTA),
      (360,RED)]

def get_beeb_colour(rgb):
    r,g,b=rgb
    hi=max(rgb)
    lo=min(rgb)
    if hi<DARK: return BLACK
    if (hi-lo)/hi<GREY_SATURATION: return WHITE if hi>=GREY_WHITE else BLACK

    if hi==r: hue=60*(g-b)/(hi-lo)
    elif hi==g: hue=120+60*(b-r)/(hi-lo)
    else: hue=240+60*(r-g)/(hi-lo)
    hue%=360

    for bound,colour in HUES:
        if hue<bound: return colour
    assert False

def main(options):
    names=['black','red','green','yellow','blue','magenta','cyan','white']
    with open(options.output,'wt') as f:
        f.write('; Generated by tools/make_tia_to_beeb.py - do not edit.\n')
        f.write('; Index with TIA colour>>1.\n')
        f.write('tia_to_beeb:\n')
        for i in range(128):
            colour=get_beeb_colour(tia_palette.get_rgb(i*2))
            f.write('                .byte %d ; $%02X %s\n'%(colour,i*2,names[colour]))

if __name__=='__main__':
    parser=argparse.ArgumentParser(description='generate TIA->BBC colour table')
    parser.add_argument('output',metavar='FILE',help='write 64tass source to %(metavar)s')
    main(parser.parse_args())
